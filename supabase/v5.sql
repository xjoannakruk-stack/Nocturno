-- =========================================================
-- 3. PARAGONY + STORAGE
-- =========================================================
create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  image_path text,
  created_at timestamptz not null default now()
);
create index if not exists receipts_employee_created_idx on public.receipts(employee_id, created_at desc);
create index if not exists receipts_created_idx on public.receipts(created_at desc);

alter table public.receipts enable row level security;
drop policy if exists "receipts_employee_insert" on public.receipts;
create policy "receipts_employee_insert"
on public.receipts for insert to authenticated
with check (employee_id=auth.uid() and exists(select 1 from public.profiles me where me.id=auth.uid() and me.active=true));

drop policy if exists "receipts_employee_select" on public.receipts;
create policy "receipts_employee_select" on public.receipts for select to authenticated
using (employee_id=auth.uid());

drop policy if exists "receipts_manager_select" on public.receipts;
create policy "receipts_manager_select" on public.receipts for select to authenticated
using (exists(select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true));

insert into storage.buckets (id,name,public)
values ('receipts','receipts',false)
on conflict (id) do update set public=false;

drop policy if exists "receipts_storage_insert" on storage.objects;
create policy "receipts_storage_insert" on storage.objects for insert to authenticated
with check (bucket_id='receipts' and ((storage.foldername(name))[1]=auth.uid()::text or exists(select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true)));

drop policy if exists "receipts_storage_select" on storage.objects;
create policy "receipts_storage_select" on storage.objects for select to authenticated
using (bucket_id='receipts' and ((storage.foldername(name))[1]=auth.uid()::text or exists(select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true)));

