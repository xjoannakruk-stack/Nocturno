create or replace function public.set_job_application_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at=now();
  return new;
end; $$;

drop trigger if exists trg_job_application_updated_at on public.job_applications;
create trigger trg_job_application_updated_at
before update on public.job_applications
for each row execute function public.set_job_application_updated_at();
-- NOCTURNO V5 - NAPRAWA LOGOWANIA / RLS
-- V4 miała rekurencyjne polityki RLS na public.profiles.

create or replace function public.is_nocturno_manager()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role='manager' and p.active=true
  );
$$;
revoke all on function public.is_nocturno_manager() from public;
grant execute on function public.is_nocturno_manager() to authenticated;

