-- 1. PROFILE / MANAGER
-- =========================================================
alter table public.profiles enable row level security;

drop policy if exists "profiles_manager_update" on public.profiles;
create policy "profiles_manager_update"
on public.profiles for update to authenticated
using (exists (select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true))
with check (exists (select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true));

drop policy if exists "profiles_manager_select" on public.profiles;
create policy "profiles_manager_select"
on public.profiles for select to authenticated
using (id=auth.uid() or exists (select 1 from public.profiles me where me.id=auth.uid() and me.role='manager' and me.active=true));

